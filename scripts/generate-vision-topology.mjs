// Regenerates vision-topology.mjs from the installed MediaPipe package, so the
// wireframe topology is never hand-transcribed. Run after changing the
// @mediapipe/tasks-vision version:  node scripts/generate-vision-topology.mjs
import { writeFileSync } from 'node:fs';
import { FaceLandmarker, GestureRecognizer } from '../node_modules/@mediapipe/tasks-vision/vision_bundle.mjs';

const sets = ['FACE_LANDMARKS_FACE_OVAL', 'FACE_LANDMARKS_LEFT_EYE', 'FACE_LANDMARKS_RIGHT_EYE',
 'FACE_LANDMARKS_LEFT_EYEBROW', 'FACE_LANDMARKS_RIGHT_EYEBROW', 'FACE_LANDMARKS_LIPS',
 'FACE_LANDMARKS_LEFT_IRIS', 'FACE_LANDMARKS_RIGHT_IRIS'];
const faceEdges = sets.flatMap(name => FaceLandmarker[name].map(edge => [edge.start, edge.end]));
// Only the landmarks the wireframe actually draws travel over the feed; the
// full 478-point mesh would triple the payload and never be rendered.
const used = [...new Set(faceEdges.flat())].sort((a, b) => a - b);
const compact = new Map(used.map((index, position) => [index, position]));
const handEdges = GestureRecognizer.HAND_CONNECTIONS.map(edge => [edge.start, edge.end]);
const body = `// Generated by scripts/generate-vision-topology.mjs. Do not edit by hand.
// FACE_WIRE_INDICES selects which MediaPipe face landmarks are transmitted;
// FACE_WIRE_EDGES joins them by position within that transmitted array.
// HAND_WIRE_EDGES indexes the 21 hand landmarks directly.
export const FACE_WIRE_INDICES = ${JSON.stringify(used)};
export const FACE_WIRE_EDGES = ${JSON.stringify(faceEdges.map(([start, end]) => [compact.get(start), compact.get(end)]))};
export const HAND_WIRE_EDGES = ${JSON.stringify(handEdges)};
`;
writeFileSync(new URL('../vision-topology.mjs', import.meta.url), body);
console.log(`vision-topology.mjs: ${used.length} face landmarks, ${faceEdges.length} face edges, ${handEdges.length} hand edges`);
