// Regenerates vision-topology.mjs from the installed MediaPipe package, so the
// skull's topology is never hand-transcribed. Run after changing the
// @mediapipe/tasks-vision version:  node scripts/generate-vision-topology.mjs
import { writeFileSync } from 'node:fs';
import { FaceLandmarker } from '../node_modules/@mediapipe/tasks-vision/vision_bundle.mjs';

const parts = {
 cranium: 'FACE_LANDMARKS_FACE_OVAL',
 leftEye: 'FACE_LANDMARKS_LEFT_EYE', rightEye: 'FACE_LANDMARKS_RIGHT_EYE',
 leftBrow: 'FACE_LANDMARKS_LEFT_EYEBROW', rightBrow: 'FACE_LANDMARKS_RIGHT_EYEBROW',
 mouth: 'FACE_LANDMARKS_LIPS',
 leftIris: 'FACE_LANDMARKS_LEFT_IRIS', rightIris: 'FACE_LANDMARKS_RIGHT_IRIS',
};
const raw = Object.fromEntries(Object.entries(parts)
 .map(([name, key]) => [name, FaceLandmarker[key].map(edge => [edge.start, edge.end])]));
// Only the landmarks the skull actually draws travel over the feed; the full
// 478-point mesh would triple the payload and never be rendered.
const used = [...new Set(Object.values(raw).flat(2))].sort((a, b) => a - b);
const compact = new Map(used.map((index, position) => [index, position]));

// Contour sets arrive as unordered edges. Walking them into closed loops is what
// lets the viewer fill an eye socket or the cranium rather than only stroke it.
// A part may hold more than one loop: lips are an outer and an inner ring.
function rings(edges) {
 const neighbours = new Map();
 for (const [a, b] of edges) {
  if (!neighbours.has(a)) neighbours.set(a, []);
  if (!neighbours.has(b)) neighbours.set(b, []);
  neighbours.get(a).push(b);
  neighbours.get(b).push(a);
 }
 const walked = new Set(), loops = [];
 for (const start of neighbours.keys()) {
  if (walked.has(start)) continue;
  const loop = [start];
  walked.add(start);
  for (let current = start; ;) {
   const next = neighbours.get(current).find(node => !walked.has(node));
   if (next === undefined) break;
   walked.add(next);
   loop.push(next);
   current = next;
  }
  if (loop.length > 2) loops.push(loop.map(index => compact.get(index)));
 }
 // Longest first, so the outer lip ring precedes the inner one.
 return loops.sort((a, b) => b.length - a.length);
}

const edges = Object.fromEntries(Object.entries(raw)
 .map(([name, list]) => [name, list.map(([a, b]) => [compact.get(a), compact.get(b)])]));
const loops = Object.fromEntries(Object.entries(raw).map(([name, list]) => [name, rings(list)]));
const body = `// Generated by scripts/generate-vision-topology.mjs. Do not edit by hand.
// FACE_WIRE_INDICES selects which MediaPipe face landmarks are transmitted.
// FACE_EDGES and FACE_RINGS both index positions within that transmitted array:
// edges stroke a part, rings are closed loops that can also be filled.
export const FACE_WIRE_INDICES = ${JSON.stringify(used)};
export const FACE_EDGES = ${JSON.stringify(edges)};
export const FACE_RINGS = ${JSON.stringify(loops)};
`;
writeFileSync(new URL('../vision-topology.mjs', import.meta.url), body);
console.log(`vision-topology.mjs: ${used.length} landmarks`);
for (const [name, list] of Object.entries(loops)) console.log(`  ${name}: ${list.map(loop => loop.length).join(' + ')}`);
